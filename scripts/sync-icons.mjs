// Turns assets/icons/*.svg (the PauliSwap duotone set exported from Figma) into
// a typed map of inner SVG markup for the <Icon> component.
import fs from 'node:fs';
import path from 'node:path';

const dir = path.resolve('assets/icons');
const entries = fs
  .readdirSync(dir)
  .filter((f) => f.endsWith('.svg') && f !== 'sprite.svg')
  .sort()
  .map((f) => {
    const svg = fs.readFileSync(path.join(dir, f), 'utf8');
    const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
    return `  '${f.replace('.svg', '')}': ${JSON.stringify(inner)},`;
  });

fs.writeFileSync(
  path.resolve('src/components/icons.ts'),
  `// Generated by scripts/sync-icons.mjs from assets/icons. Do not edit by hand.\n` +
    `export const ICONS = {\n${entries.join('\n')}\n} as const;\n\nexport type IconName = keyof typeof ICONS;\n`,
);
console.log(`wrote ${entries.length} icons`);
